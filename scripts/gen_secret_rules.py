#!/usr/bin/env python3
"""Generate internal/secretscan/rules_gen.go from vendored gitleaks rule data.

The runtime scanner must stay dependency-free, so the TOML rule data is converted
into Go structures at development time. This script only runs for maintainers
(Python 3.11+ standard library `tomllib`); it is not part of the build.

Usage:
    python3 scripts/gen_secret_rules.py
    python3 scripts/gen_secret_rules.py --toml internal/secretscan/rules/gitleaks.toml \
        --out internal/secretscan/rules_gen.go --version v8.30.1 --commit 83d9cd6
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

try:
    import tomllib
except ModuleNotFoundError:  # pragma: no cover - maintainer convenience only
    sys.exit("python3.11+ is required (tomllib)")

ROOT = Path(__file__).resolve().parent.parent
DEFAULT_TOML = ROOT / "internal" / "secretscan" / "rules" / "gitleaks.toml"
DEFAULT_OUT = ROOT / "internal" / "secretscan" / "rules_gen.go"
DEFAULT_VERSION = "v8.30.1"
DEFAULT_COMMIT = "83d9cd684c87d95d656c1458ef04895a7f1cbd8e"

HEADER = """\
// Code generated by scripts/gen_secret_rules.py from
// internal/secretscan/rules/gitleaks.toml ({version}, commit {commit});
// DO NOT EDIT.
//
// Upstream: https://github.com/gitleaks/gitleaks
// License: MIT, Copyright (c) 2019 Zachary Rice. See
// internal/secretscan/rules/LICENSE for the full text.
//
// Regenerate with: just sync-secret-rules

package secretscan
"""


def go_string(value: str) -> str:
    """Return a valid Go string literal for value."""
    if "`" not in value and "\r" not in value:
        return "`" + value + "`"
    quoted = ['"']
    for ch in value:
        if ch == '"':
            quoted.append('\\"')
        elif ch == "\\":
            quoted.append("\\\\")
        elif ch == "\n":
            quoted.append("\\n")
        elif ch == "\t":
            quoted.append("\\t")
        elif ch == "\r":
            quoted.append("\\r")
        elif ord(ch) < 0x20:
            quoted.append(f"\\x{ord(ch):02x}")
        else:
            quoted.append(ch)
    quoted.append('"')
    return "".join(quoted)


def go_strings(values: list[str]) -> str:
    rendered = ", ".join(go_string(v) for v in values)
    return "[]string{" + rendered + "}"


def emit_allowlist(allowlist: dict, indent: str) -> str:
    lines = [indent + "{"]
    field_indent = indent + "\t"
    if allowlist.get("description"):
        lines.append(field_indent + "Description: " + go_string(allowlist["description"]) + ",")
    condition = allowlist.get("condition") or ""
    if condition.upper() == "AND":
        lines.append(field_indent + "Condition: allowlistAND,")
    elif condition.upper() not in ("", "OR"):
        sys.exit(f"unsupported allowlist condition: {condition!r}")
    if allowlist.get("paths"):
        lines.append(field_indent + "Paths: " + go_strings(list(allowlist["paths"])) + ",")
    if allowlist.get("regexes"):
        lines.append(field_indent + "Regexes: " + go_strings(list(allowlist["regexes"])) + ",")
    if allowlist.get("regexTarget"):
        lines.append(field_indent + "RegexTarget: " + go_string(allowlist["regexTarget"]) + ",")
    if allowlist.get("stopwords"):
        lines.append(field_indent + "Stopwords: " + go_strings(list(allowlist["stopwords"])) + ",")
    lines.append(indent + "},")
    return "\n".join(lines)


def normalize_allowlists(raw_rule: dict) -> list[dict]:
    """gitleaks accepts both the deprecated `allowlist` and `allowlists` keys."""
    if raw_rule.get("allowlists"):
        return list(raw_rule["allowlists"])
    if raw_rule.get("allowlist"):
        return [raw_rule["allowlist"]]
    return []


def emit_rule(rule: dict) -> str:
    lines = ["\t{"]
    lines.append('\t\tID: ' + go_string(str(rule["id"])) + ",")
    if rule.get("regex"):
        lines.append('\t\tRegex: ' + go_string(rule["regex"]) + ",")
    if rule.get("secretGroup"):
        lines.append(f'\t\tSecretGroup: {int(rule["secretGroup"])},')
    if rule.get("entropy"):
        lines.append(f'\t\tEntropy: {rule["entropy"]!r},')
    if rule.get("keywords"):
        lines.append('\t\tKeywords: ' + go_strings(list(rule["keywords"])) + ",")
    if rule.get("path"):
        lines.append('\t\tPath: ' + go_string(rule["path"]) + ",")
    allowlists = normalize_allowlists(rule)
    if allowlists:
        lines.append("\t\tAllowlists: []allowlist{")
        for allowlist in allowlists:
            nested = emit_allowlist(allowlist, "\t\t\t")
            lines.append(nested)
        lines.append("\t\t},")
    lines.append("\t},")
    return "\n".join(lines)


def generate(toml_path: Path, version: str, commit: str) -> str:
    data = tomllib.loads(toml_path.read_text(encoding="utf-8"))
    rules = data.get("rules") or []
    if not rules:
        sys.exit(f"no [[rules]] found in {toml_path}")

    global_allowlists = []
    for key in ("allowlist", "allowlists"):
        if data.get(key):
            value = data[key]
            global_allowlists.extend(value if isinstance(value, list) else [value])
    # `allowlist` and `allowlists` are mutually exclusive upstream; be defensive.
    if data.get("allowlist") and data.get("allowlists"):
        sys.exit("both [allowlist] and [[allowlists]] present; check the vendored TOML")

    chunks = [HEADER.format(version=version, commit=commit)]
    chunks.append("// gitleaksRules mirrors the [[rules]] entries of the default gitleaks config.")
    chunks.append("var gitleaksRules = []rule{")
    for rule in rules:
        chunks.append(emit_rule(rule))
    chunks.append("}")
    chunks.append("")
    chunks.append("// gitleaksGlobalAllowlists mirrors the global allowlist of the default gitleaks config.")
    chunks.append("var gitleaksGlobalAllowlists = []allowlist{")
    for allowlist in global_allowlists:
        chunks.append(emit_allowlist(allowlist, "\t"))
    chunks.append("}")
    chunks.append("")
    return "\n".join(chunks)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--toml", type=Path, default=DEFAULT_TOML)
    parser.add_argument("--out", type=Path, default=DEFAULT_OUT)
    parser.add_argument("--version", default=DEFAULT_VERSION)
    parser.add_argument("--commit", default=DEFAULT_COMMIT)
    args = parser.parse_args()

    if not args.toml.exists():
        sys.exit(f"rule data not found: {args.toml}")

    content = generate(args.toml, args.version, args.commit)
    args.out.write_text(content, encoding="utf-8")
    print(f"generated {args.out} ({len(content)} bytes) from {args.toml}")


if __name__ == "__main__":
    main()
